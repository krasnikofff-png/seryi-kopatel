function tighten(t, by) {
  if (!t.shown) return;
  t.shown.r = Math.max(t.real.r + 6, t.shown.r - by * TS);
  t.shown.x = (t.shown.x + t.real.x) / 2;
  t.shown.y = (t.shown.y + t.real.y) / 2;
}
